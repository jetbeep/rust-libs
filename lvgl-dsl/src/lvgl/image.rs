/// LVGL image widget (`lv_image`).
///
/// Displays a static image from a C array descriptor or a file-system path.
/// Supports offset, uniform scaling, and rotation around a configurable pivot.
///
/// # Kconfig requirements
/// `CONFIG_LV_USE_IMAGE=y`
///
/// # Example
/// ```ignore
/// use lvgl_dsl::lvgl::prelude::*;
///
/// // C descriptor (unsafe):
/// // extern "C" { static MY_ICON: core::ffi::c_void; }
/// let src = unsafe { ImageSrc::descriptor(&raw const MY_ICON) };
///
/// let img = Image::new(&screen)
///     .set_src(src)
///     .set_scale(256)           // 1:1 (256 = 100 %)
///     .set_rotation(0)
///     .align(LvAlign::Center, 0, 0);
///
/// // File path (safe):
/// let src = ImageSrc::file("S:icons/logo.bin")?;
///
/// let img = Image::new(&screen)
///     .set_src(src)
///     .size(Size::Px(64), Size::Px(64));
/// ```
pub struct Image {
    obj: LvObj,
}

/// Mirrors LVGL's `lv_image_align_t`. Values must match the C enum in
/// `lv_image.h` (LVGL v9).
#[repr(u32)]
#[derive(Copy, Clone, Debug, PartialEq, Eq)]
pub enum LvImageAlign {
    Default = 0,
    TopLeft = 1,
    TopMid = 2,
    TopRight = 3,
    BottomLeft = 4,
    BottomMid = 5,
    BottomRight = 6,
    LeftMid = 7,
    RightMid = 8,
    Center = 9,
    /// Independently scales X and Y to fill the widget's area. The
    /// widget's size MUST be set explicitly (auto-size to source is
    /// otherwise the default).
    Stretch = 11,
    Tile = 12,
    Contain = 13,
    Cover = 14,
}

impl Widget for Image {
    fn lv_obj(&self) -> &LvObj {
        &self.obj
    }
}

impl Image {
    /// Creates a new image widget as a child of `parent`.
    ///
    /// # Panics
    /// Panics if LVGL returns a null pointer (out-of-memory or
    /// `LV_USE_IMAGE` not enabled in Kconfig).
    pub fn new(parent: &impl Widget) -> Image {
        // SAFETY: `parent` wraps a non-null, valid LVGL object.
        let obj = unsafe { c_bindings::lv_image_create(parent.lv_obj().raw()) };
        if obj.is_null() {
            panic!("lv_image_create returned null — check CONFIG_LV_USE_IMAGE=y");
        }
        Image {
            obj: LvObj::from_raw(obj),
        }
    }

    /// Sets the image source and retains it until this LVGL object is deleted.
    pub fn set_src(&self, src: ImageSrc) -> &Self {
        let obj = self.lv_obj().raw();
        set_retained_src_for_obj(obj, ImageRetentionSlot::Source, src, |src_ptr| unsafe {
            c_bindings::lv_image_set_src(obj, src_ptr);
        });
        self
    }

    /// Shifts the image by `(x, y)` pixels relative to its normal position.
    pub fn set_offset(&self, x: i32, y: i32) -> &Self {
        unsafe {
            c_bindings::lv_image_set_offset_x(self.lv_obj().raw(), x);
            c_bindings::lv_image_set_offset_y(self.lv_obj().raw(), y);
        }
        self
    }

    /// Sets the scale factor.  `256` = 100 % (no scaling), `128` = 50 %,
    /// `512` = 200 %.
    pub fn set_scale(&self, factor: u32) -> &Self {
        unsafe { c_bindings::lv_image_set_scale(self.lv_obj().raw(), factor) };
        self
    }

    /// Sets the rotation angle in tenths of degrees.
    ///
    /// `10` units = 1°, so `900` = 90°, `3600` = 360°. Values outside
    /// 0–3600 are wrapped by LVGL. Rotation is applied around the pivot
    /// set by [`set_pivot`](Image::set_pivot).
    pub fn set_rotation(&self, angle: i32) -> &Self {
        unsafe { c_bindings::lv_image_set_rotation(self.lv_obj().raw(), angle) };
        self
    }

    /// Sets the pivot point for rotation and scaling, in pixels relative to
    /// the top-left corner of the image.
    pub fn set_pivot(&self, x: i32, y: i32) -> &Self {
        unsafe { c_bindings::lv_image_set_pivot(self.lv_obj().raw(), x, y) };
        self
    }

    /// Sets how the bitmap is positioned/sized inside the widget's bounding
    /// box. The default (`LvImageAlign::Default`) draws the bitmap at its
    /// native size from the widget's top-left. `LvImageAlign::Stretch`
    /// scales the X and Y axes independently so the bitmap fills the
    /// widget's area exactly — useful when overlays must align to a
    /// known coordinate space and the widget size is set explicitly.
    pub fn set_inner_align(&self, align: LvImageAlign) -> &Self {
        unsafe { c_bindings::lv_image_set_inner_align(self.lv_obj().raw(), align as u32) };
        self
    }

    /// Sets the tint color blended over the rendered image
    /// (`LV_PART_MAIN | LV_STATE_DEFAULT`).
    ///
    /// Has no visible effect until [`recolor_opa`](Self::recolor_opa)
    /// is set to a non-zero value. Works for any image source
    /// including SVG, since the recolor is applied on the post-decode
    /// raster while preserving alpha.
    pub fn recolor(&self, color: crate::lvgl::color::Color) -> &Self {
        unsafe {
            c_bindings::lv_obj_set_style_image_recolor(
                self.lv_obj().raw(),
                color.to_lv(),
                0,
            );
        }
        self
    }

    /// Sets the opacity of the tint color set by [`recolor`](Self::recolor)
    /// (`LV_PART_MAIN | LV_STATE_DEFAULT`).
    ///
    /// `0` keeps the original colors, `255` fully replaces them with the
    /// recolor value, intermediate values blend.
    pub fn recolor_opa(&self, opa: u8) -> &Self {
        unsafe {
            c_bindings::lv_obj_set_style_image_recolor_opa(
                self.lv_obj().raw(),
                opa,
                0,
            );
        }
        self
    }

    /// Resets the tint by setting `recolor_opa` to `0`.
    ///
    /// The recolor *color* set by [`recolor`](Self::recolor) is left
    /// untouched — it just becomes invisible. Equivalent to calling
    /// `recolor_opa(0)` but reads better at call sites that want to
    /// say "no tint right now".
    pub fn clear_recolor(&self) -> &Self {
        self.recolor_opa(0)
    }
}

