// ============================================================
//  ImageSrc — source pointer for LVGL images
// ============================================================

/// A source pointer that can refer to either a C image descriptor array
/// (`const lv_image_dsc_t *`) or a file-system path string.
///
/// # Safety
///
/// LVGL does not copy the source data — the pointed-to memory must remain
/// valid for as long as the image widget exists. Safe DSL setters consume
/// `ImageSrc` and retain it until the LVGL object is deleted.
///
/// # Examples
///
/// ```ignore
/// // From a C image array generated by LVGL's image converter tool:
/// extern "C" { static my_icon: c_void; }
/// let src = unsafe { ImageSrc::descriptor(&raw const my_icon) };
///
/// // From a file path on LittleFS / FAT:
/// let src = ImageSrc::file("S:icons/logo.bin")?;
/// ```
#[derive(Clone)]
pub struct ImageSrc {
    kind: ImageSrcKind,
}

#[derive(Clone)]
enum ImageSrcKind {
    Descriptor(*const c_void),
    File(CString),
    StaticFile(&'static CStr),
}

// SAFETY: LVGL image descriptors are expected to point to immutable global data;
// file paths are either owned immutable CString buffers or static CStr literals.
unsafe impl Send for ImageSrc {}
unsafe impl Sync for ImageSrc {}

impl ImageSrc {
    /// Creates an `ImageSrc` from a pointer to a C `lv_image_dsc_t` descriptor.
    ///
    /// # Safety
    /// - `ptr` must be non-null and point to a valid `lv_image_dsc_t` that
    ///   lives at least as long as every widget that uses this source.
    /// - The pointed-to data must be safe to access from any thread
    ///   (`Send + Sync`), since `ImageSrc` implements both traits.
    #[inline]
    pub unsafe fn descriptor(ptr: *const c_void) -> Self {
        debug_assert!(
            !ptr.is_null(),
            "ImageSrc::descriptor called with null pointer"
        );
        Self {
            kind: ImageSrcKind::Descriptor(ptr),
        }
    }

    /// Creates an `ImageSrc` from a file-system path.
    ///
    /// The path is copied into an owned, NUL-terminated buffer because LVGL
    /// stores the pointer directly. Safe DSL setters retain the returned
    /// `ImageSrc` until the LVGL object is deleted.
    #[inline]
    pub fn file(path: &str) -> Result<Self, NulError> {
        Ok(Self {
            kind: ImageSrcKind::File(CString::new(path)?),
        })
    }

    /// Creates an `ImageSrc` from a static C string path without allocation.
    ///
    /// This is useful for low-level callers that already have a static C string.
    /// Most application code should use [`ImageSrc::file`] with a Rust `&str`.
    #[inline]
    pub const fn file_cstr(path: &'static CStr) -> Self {
        Self {
            kind: ImageSrcKind::StaticFile(path),
        }
    }

    /// Returns the raw pointer passed to LVGL's `lv_image_set_src` /
    /// `lv_obj_set_style_bg_image_src` calls.
    #[inline]
    pub(crate) fn as_ptr(&self) -> *const c_void {
        match &self.kind {
            ImageSrcKind::Descriptor(ptr) => *ptr,
            ImageSrcKind::File(path) => path.as_ptr().cast::<c_void>(),
            ImageSrcKind::StaticFile(path) => path.as_ptr().cast::<c_void>(),
        }
    }
}

#[derive(Copy, Clone, PartialEq, Eq, PartialOrd, Ord)]
pub(crate) enum ImageRetentionSlot {
    Source,
    ImageButtonState(u32),
    Background,
}

type ImageRetentionKey = (usize, ImageRetentionSlot);

#[cfg(test)]
std::thread_local! {
    static IMAGE_RETENTION_STORE: RefCell<BTreeMap<ImageRetentionKey, *mut ImageSrc>> =
        RefCell::new(BTreeMap::new());
}

#[cfg(not(test))]
struct ImageRetentionStore {
    locked: AtomicBool,
    sources: UnsafeCell<Option<BTreeMap<ImageRetentionKey, *mut ImageSrc>>>,
}

#[cfg(not(test))]
// SAFETY: LVGL object APIs are only valid from the UI thread. The store is
// mutated only as part of those UI-thread calls and delete-event callbacks.
unsafe impl Sync for ImageRetentionStore {}

#[cfg(not(test))]
static IMAGE_RETENTION_STORE: ImageRetentionStore = ImageRetentionStore {
    locked: AtomicBool::new(false),
    sources: UnsafeCell::new(None),
};

#[cfg(test)]
fn with_image_retention_store<R>(
    f: impl FnOnce(&mut BTreeMap<ImageRetentionKey, *mut ImageSrc>) -> R,
) -> R {
    IMAGE_RETENTION_STORE.with(|store| f(&mut store.borrow_mut()))
}

#[cfg(not(test))]
fn with_image_retention_store<R>(
    f: impl FnOnce(&mut BTreeMap<ImageRetentionKey, *mut ImageSrc>) -> R,
) -> R {
    while IMAGE_RETENTION_STORE
        .locked
        .compare_exchange(false, true, Ordering::Acquire, Ordering::Relaxed)
        .is_err()
    {
        core::hint::spin_loop();
    }
    struct Unlock;
    impl Drop for Unlock {
        fn drop(&mut self) {
            IMAGE_RETENTION_STORE
                .locked
                .store(false, Ordering::Release);
        }
    }
    let _unlock = Unlock;

    let store = unsafe { &mut *IMAGE_RETENTION_STORE.sources.get() };
    if store.is_none() {
        *store = Some(BTreeMap::new());
    }
    f(store.as_mut().expect("image retention store initialized"))
}

pub(crate) fn set_retained_src_for_obj(
    obj: *mut c_bindings::lv_obj_t,
    slot: ImageRetentionSlot,
    src: ImageSrc,
    apply: impl FnOnce(*const c_void),
) {
    // Keep the old source alive until after LVGL is updated to the new pointer.
    let src_ptr = src.as_ptr();
    let retained = Box::into_raw(Box::new(src));
    unsafe {
        c_bindings::lv_obj_add_event_cb(
            obj,
            Some(drop_retained_image_src),
            c_bindings::LV_EVENT_DELETE,
            retained.cast::<c_void>(),
        );
    }
    let previous =
        with_image_retention_store(|store| store.insert((obj as usize, slot), retained));
    apply(src_ptr);
    if let Some(previous) = previous {
        unsafe {
            c_bindings::lv_obj_remove_event_cb_with_user_data(
                obj,
                Some(drop_retained_image_src),
                previous.cast::<c_void>(),
            );
            drop(Box::from_raw(previous));
        }
    }
}

unsafe extern "C" fn drop_retained_image_src(e: *mut c_bindings::lv_event_t) {
    let retained = unsafe { c_bindings::lv_event_get_user_data(e) }.cast::<ImageSrc>();
    if !retained.is_null() {
        drop_retained_ptr(retained);
    }
}

fn drop_retained_ptr(retained: *mut ImageSrc) {
    let removed = with_image_retention_store(|store| {
        let key = store
            .iter()
            .find_map(|(key, ptr)| (*ptr == retained).then_some(*key));
        key.and_then(|key| store.remove(&key))
    });
    if let Some(retained) = removed {
        unsafe {
            drop(Box::from_raw(retained));
        }
    }
}

#[cfg(test)]
pub(crate) fn retained_image_src_count() -> usize {
    with_image_retention_store(|store| store.len())
}

#[cfg(test)]
pub(crate) fn reset_retained_image_srcs() {
    let retained = with_image_retention_store(|store| {
        let retained = store.values().copied().collect::<alloc::vec::Vec<_>>();
        store.clear();
        retained
    });
    for retained in retained {
        unsafe {
            drop(Box::from_raw(retained));
        }
    }
}

